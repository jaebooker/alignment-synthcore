"""Generate a room-size variant of the vendored gw.py; ppo.py is copied byte-identical.
Only the room constants change: grid side, interior range, proxy corner, horizon."""
import sys, shutil, hashlib
from pathlib import Path
R, T = int(sys.argv[1]), int(sys.argv[2])
V = Path(sys.argv[3]); out = Path(sys.argv[4]); out.mkdir(parents=True, exist_ok=True)
s = (V / "gw.py").read_text()
subs = [("G = 9            # full grid incl. border", f"G = {R + 2}            # full grid incl. border"),
        ("LO, HI = 1, 7    # interior coordinate range (inclusive)", f"LO, HI = 1, {R}    # interior coordinate range (inclusive)"),
        ("CORNER = jnp.array([1, 7])", f"CORNER = jnp.array([1, {R}])"),
        ("T_MAX = 20", f"T_MAX = {T}"),
        ("    cor = np.array([1, 7])", f"    cor = np.array([1, {R}])")]
for a, b in subs:
    assert s.count(a) == 1, a
    s = s.replace(a, b)
s = s.replace('"""Gridworld testbed', f'"""[Room-size variant R={R}, T_MAX={T}, generated by make_env.py from the vendored gw.py]\nGridworld testbed', 1)
(out / "gw.py").write_text(s)
shutil.copy(V / "ppo.py", out / "ppo.py")
print({f: hashlib.sha256((out / f).read_bytes()).hexdigest()[:12] for f in ("gw.py", "ppo.py")})
