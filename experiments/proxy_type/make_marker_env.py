"""Generate the visible-marker proxy variant from the vendored gw.py/ppo.py.
Proxy = a visible marker object (4th observation channel) instead of the implicit corner.
Training: gem at a uniform random cell; marker on the gem in 1-p of episodes, at a different random
cell in p of them. Reward only for the gem (terminal); the marker is not terminal in training.
ppo.py changes: 4 input channels and passing the marker to obs_fn; nothing else."""
import sys
from pathlib import Path
V, out = Path(sys.argv[1]), Path(sys.argv[2]); out.mkdir(parents=True, exist_ok=True)
g = (V / "gw.py").read_text()
subs = [
("""def obs_fn(agent, gem):
    a = jnp.zeros((G, G)).at[agent[0], agent[1]].set(1.0)
    g = jnp.zeros((G, G)).at[gem[0], gem[1]].set(1.0)
    return jnp.stack([WALL, a, g], axis=-1)  # (9, 9, 3)""",
"""def obs_fn(agent, gem, marker):
    a = jnp.zeros((G, G)).at[agent[0], agent[1]].set(1.0)
    g = jnp.zeros((G, G)).at[gem[0], gem[1]].set(1.0)
    m = jnp.zeros((G, G)).at[marker[0], marker[1]].set(1.0)
    return jnp.stack([WALL, a, g, m], axis=-1)  # (9, 9, 4)"""),
("""    decor = jax.random.uniform(k1) < p
    gem = jnp.where(decor, _rand_cell(k2), CORNER)
""",
"""    k1, k4 = jax.random.split(k1)
    decor = jax.random.uniform(k1) < p
    gem = _rand_cell(k2)

    def mbody(carry):
        k, _ = carry
        k, sub = jax.random.split(k)
        return k, _rand_cell(sub)

    _, other = jax.lax.while_loop(lambda c: jnp.all(c[1] == gem), mbody, (k4, gem))
    marker = jnp.where(decor, other, gem)
"""),
("    return dict(agent=agent, gem=gem, t=jnp.array(0))", "    return dict(agent=agent, gem=gem, marker=marker, t=jnp.array(0))"),
("    new = dict(agent=agent, gem=state[\"gem\"], t=t)", "    new = dict(agent=agent, gem=state[\"gem\"], marker=state[\"marker\"], t=t)"),
("    return state, obs_fn(state[\"agent\"], state[\"gem\"]), reward, done", "    return state, obs_fn(state[\"agent\"], state[\"gem\"], state[\"marker\"]), reward, done"),
]
for a, b in subs:
    assert g.count(a) == 1, a[:60]
    g = g.replace(a, b)
g = '"""[Visible-marker proxy variant, generated by make_marker_env.py from the vendored gw.py]\n' + g.lstrip('"')
(out / "gw.py").write_text(g)
p = (V / "ppo.py").read_text()
psubs = [("        d = gw.G * gw.G * 3\n", "        d = gw.G * gw.G * 4\n"),
         ("    return dict(c1=conv(ks[0], 3, c), c2=conv(ks[1], c, c),", "    return dict(c1=conv(ks[0], 4, c), c2=conv(ks[1], c, c),"),
         ("        obs = jax.vmap(gw.obs_fn)(states[\"agent\"], states[\"gem\"])\n", "        obs = jax.vmap(gw.obs_fn)(states[\"agent\"], states[\"gem\"], states[\"marker\"])\n")]
for a, b in psubs:
    assert p.count(a) == 1, a
    p = p.replace(a, b)
(out / "ppo.py").write_text(p)
print("ok")
